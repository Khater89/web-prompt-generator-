import {copyFile,mkdir,readFile,writeFile} from 'node:fs/promises';
const shared=new URL('../supabase/functions/_shared/',import.meta.url);
await mkdir(shared,{recursive:true});
for(const name of ['schema.mjs','research.mjs'])await copyFile(new URL('../server/'+name,import.meta.url),new URL(name,shared));
const inputs=[
 ['schema.mjs',null],
 ['research.mjs',"import {researchSchema,validate} from './schema.mjs';\n"],
 ['handler.mjs',"import {researchProject,ResearchError} from './research.mjs';\n"]
];
const parts=[];
for(const [name,knownImport] of inputs){
 let source=await readFile(new URL(name,shared),'utf8');
 if(knownImport){if(!source.startsWith(knownImport))throw Error('Unexpected dependencies in '+name);source=source.slice(knownImport.length);}
 source=source.replace(/^export (?=(const|function|class|async function)\b)/gm,'');
 if(/^\s*(import|export)\b/m.test(source))throw Error('Unbundled module dependency in '+name);
 parts.push('// Included source: '+name+'\n'+source.trim());
}
const bundle='// @ts-nocheck\n// Project Forge: self-contained Supabase Edge Function.\n// Generated by scripts/sync-supabase.mjs; suitable for Dashboard index.ts and CLI.\n// No imports, sibling files, SDK downloads or embedded API secrets are required.\n\n'+parts.join('\n\n')+'\n\nDeno.serve(createSupabaseHandler(Deno.env.toObject()));\n';
await writeFile(new URL('../supabase/functions/ai-assist/index.ts',import.meta.url),bundle);
console.log('Supabase modules synchronized; self-contained ai-assist/index.ts generated.');
